import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { PORTABLE_LOOM_MATH_SOURCE_PATHS } from '../app/engine/portable-loom-tomography-fixtures.js';

// Pin the exact carried source set and CLI companion. This is a build-time
// consistency declaration, never authentication of upstream or empirical origin.
const root=new URL('../',import.meta.url),target=new URL('app/engine/portable-loom-tomography-assets.js',root);
const hash=bytes=>createHash('sha256').update(bytes).digest('hex');
const sources=await Promise.all(PORTABLE_LOOM_MATH_SOURCE_PATHS.map(async path=>({path,sha256:hash(await readFile(new URL(path,root)))})));
const companion=await readFile(new URL('scripts/portable-loom-tomography-audit.mjs',root),'utf8');
const body='// Generated by scripts/sync-portable-loom-tomography-assets.mjs.\n'
  +'// Hashes witness carried-byte consistency, not external source authenticity.\n'
  +'export const PORTABLE_LOOM_MATH_ASSETS = Object.freeze('+JSON.stringify(sources,null,2)+'.map(Object.freeze));\n'
  +'export const PORTABLE_LOOM_COMPANION_SHA256 = '+JSON.stringify(hash(companion))+';\n'
  +'export const PORTABLE_LOOM_COMPANION_SOURCE = '+JSON.stringify(companion)+';\n';
if(process.argv.includes('--check')){
  if(await readFile(target,'utf8').catch(()=>null)!==body)throw new Error('PORTABLE_LOOM_MATH_ASSETS_DRIFT: run node scripts/sync-portable-loom-tomography-assets.mjs');
  console.log('Portable Loom mathematical sources and companion: exact generated-byte parity.');
}else await writeFile(target,body);
